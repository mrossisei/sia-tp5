# Etiquetas (caracteres) para anotar el scatter latente. 0x60..0x7f.
LABELS = [
    "`", "a", "b", "c", "d", "e", "f", "g", "h", "i", "j", "k", "l", "m",
    "n", "o", "p", "q", "r", "s", "t", "u", "v", "w", "x", "y", "z",
    "{", "|", "}", "~", "DEL",
]

ROWS, COLS = 7, 5
INPUT_DIM = ROWS * COLS  # 35


def to_bin_array(encoded_char):
    """Decodifica un patrón (7 enteros) a una matriz binaria (7, 5).

    Réplica exacta de material/fonts.ipynb.
    """
    bin_array = np.zeros((ROWS, COLS), dtype=int)
    for row in range(ROWS):
        current = encoded_char[row]
        for col in range(COLS):
            bin_array[row][COLS - 1 - col] = current & 1
            current >>= 1
    return bin_array


def load_font(flatten=True):
    """Devuelve (X, labels).

    X: (32, 35) float en {0,1} si flatten, o (32, 7, 5) si no.
    labels: lista de 32 nombres de caracter ('`','a',...,'DEL').
    """
    patterns = np.stack([to_bin_array(c) for c in FONT3]).astype(np.float64)
    if flatten:
        patterns = patterns.reshape(len(FONT3), INPUT_DIM)
    return patterns, list(LABELS)
